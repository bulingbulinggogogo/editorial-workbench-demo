const fs=require('node:fs'),vm=require('node:vm'),assert=require('node:assert/strict');
const ctx=vm.createContext({structuredClone,crypto:require('node:crypto').webcrypto});
vm.runInContext(fs.readFileSync('book-directory.js','utf8'),ctx);
const parse=ctx.parseDirectoryBatch;
const rows=parse('第一部分\n\t第一单元\n\t\t[套题] Test 1\n\t\t[套题] Test 2\n第二部分');
assert.equal(rows.length,5);assert.equal(rows[2].kind,'套题');assert.equal(rows[2].parentId,rows[1].id);assert.equal(rows[4].parentId,'');
assert.equal(parse('目录\n    [套题] Test 1')[1].depth,1);
assert.throws(()=>parse('\t目录'),/跳级/);
assert.throws(()=>parse('[套题] Test 1\n\t子目录'),/套题.*下不能/);
assert.throws(()=>parse('[套题]'),/填写名称/);
assert.throws(()=>parse('重复\n重复'),/已存在/);
assert.throws(()=>parse('目录','suite',[{id:'suite',kind:'套题'}]),/上级目录/);
assert.throws(()=>parse('目录','root',[{id:'root',kind:'目录'},{id:'old',parentId:'root',name:'目录'}]),/已存在/);
assert.equal(parse('套题内容','root',[{id:'root',kind:'目录'}])[0].parentId,'root');
const transform=ctx.transformDirectoryLines;
assert.equal(transform('A\nB\nC',0,4,'suite').text,'[套题] A\n[套题] B\nC');
assert.equal(transform('\t[套题] A',0,8,'directory').text,'\tA');
assert.equal(transform('A\nB',0,3,'indent').text,'\tA\n\tB');
assert.equal(transform('\tA\n    B',0,9,'outdent').text,'A\nB');
assert.throws(()=>ctx.updateDirectoryNode([{id:'suite',kind:'套题'}],null,{name:'A',parentId:'suite'}),/不能创建/);
console.log('PASS: batch hierarchy, suite constraints, duplicates, parent selection, multi-line marking and indentation');
const tree=[{id:'a',parentId:'',kind:'目录'},{id:'child',parentId:'a',kind:'套题',sourceSuiteId:'123'},{id:'b',parentId:'',kind:'目录'},{id:'c',parentId:'',kind:'目录'}];
const ordered=ctx.reorderBookDirectory(tree,'a','c',true);
assert.equal(ordered.filter(n=>!n.parentId).map(n=>n.id).join(','),'b,c,a');
assert.equal(ordered.find(n=>n.id==='child').parentId,'a');
assert.equal(ordered.find(n=>n.id==='child').sourceSuiteId,'123');
assert.equal(tree[0].id,'a');
assert.throws(()=>ctx.reorderBookDirectory(tree,'child','b'),/同一上级/);
console.log('PASS: directory reordering preserves hierarchy and source associations');
